#!/usr/bin/env python3
"""Regenerate TextSearchCore's pinned Unicode 16.0.0 full case-fold table.

Run with Python 3.14 (whose unicodedata version is 16.0.0):
  python3.14 scripts/generate-case-folding.py

Python's str.casefold uses Unicode's default full case folding (C + F entries,
excluding Turkic T entries). See Unicode 16.0.0 CaseFolding.txt:
https://www.unicode.org/Public/16.0.0/ucd/CaseFolding.txt
"""

from pathlib import Path
import unicodedata


assert unicodedata.unidata_version == "16.0.0", unicodedata.unidata_version

root = Path(__file__).resolve().parent.parent
target = root / "Sources/TextSearchCore/UnicodeCaseFolding.swift"

lines = [
    "// Generated by scripts/generate-case-folding.py using Python 3.14 and",
    "// Unicode 16.0.0. Source: https://www.unicode.org/Public/16.0.0/ucd/CaseFolding.txt",
    "// Entries are default full case folding (C + F; no Turkic T mappings).",
    "// Do not edit this table manually.",
    "",
    "enum UnicodeCaseFolding {",
    "    static func fold(_ scalar: Unicode.Scalar) -> [Unicode.Scalar] {",
    "        if scalar.value < 128 {",
    "            let value = scalar.value",
    "            return [Unicode.Scalar((65...90).contains(value) ? value + 32 : value)!]",
    "        }",
    "        guard let mapping = mappings[scalar.value] else { return [scalar] }",
    "        return Array(mapping.unicodeScalars)",
    "    }",
    "",
    "    private static let mappings: [UInt32: String] = [",
]

for value in range(128, 0x110000):
    if 0xD800 <= value <= 0xDFFF:
        continue
    folded = chr(value).casefold()
    if folded != chr(value):
        codepoints = "".join(f"\\u{{{ord(char):X}}}" for char in folded)
        lines.append(f'        0x{value:04X}: "{codepoints}",')

lines.extend(["    ]", "}", ""])
target.write_text("\n".join(lines), encoding="utf-8")
